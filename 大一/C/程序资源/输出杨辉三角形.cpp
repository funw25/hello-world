//编程在屏幕上输出如下所示的杨辉三角形。
//杨辉三角的规律是：每行的第1个与最后1个数均为1；
//杨辉三角除了两端为1以外，
//其余的各数都等于它上一行左边列和上一行同列的两数之和。
//    1
//    1    1
//    1    2    1
//    1    3    3    1
//    1    4    6    4    1
#include <stdio.h>
int main() {
    int n=5;  // 定义杨辉三角的行数，这里示例为5行，可根据需求修改
    int a[100][100];  // 二维数组用于存储杨辉三角的数值，这里假设最大100行，可按需调整
    // 初始化杨辉三角的第一列和对角线元素（均为1）
    for(int i=0;i<n;i++){
    	a[i][0]=1;
        a[i][i]=1;
    }
    // 根据杨辉三角的规律计算中间的元素
    for(int i=2;i<n;i++){
        for(int j=1;j<i;j++){
            a[i][j]=a[i-1][j-1]+a[i-1][j];
        }
    }

    // 输出杨辉三角
    for(int i=0;i<n;i++) {
        for(int j=0;j<=i;j++) {
            printf("%d ",a[i][j]);
        }
        printf("\n");
    }
    return 0;
}
