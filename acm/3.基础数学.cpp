//快速幂的非递归实现（循环）
int power(int a, int n)
   {
	   int ans = 1;
	   while (n)
	   {
		   if (n % 2)
			   ans = ans * a;
		   a = a * a;
		   n = n / 2;
	   }
	   return ans;
   }

