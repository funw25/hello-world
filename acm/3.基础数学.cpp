//快速幂的递归实现
int power(int a, int n)//底数和指数
{
	int ans;
	if (n == 0)
		ans = 1;//结束条件
	else
	{
		ans = power(a * a, n / 2);//这里n除以2 是整除 如果n是奇数怎么办？
		if (n % 2 == 1)//如果n是奇数，乘上一个底数就行了
			ans *= a;
	}
	return ans;
}


